// GETTING-ON-AIR.md — the playout-side quick guide bundled into exported packages.
// A condensed, package-local edition of docs/PLAYOUT_INTEGRATION.md, written for the person
// configuring the playout machine (who never sees this repo). Keep the two in agreement:
// anything corrected here is usually wrong in the doc too.
//
// THE GUIDE ONLY DESCRIBES WHAT IS IN THE FOLDER (student-release acceptance, 2026-08-05).
// One text served every flavour, so an SPX or CasparCG package — which carries no relay on
// purpose, because the playout host is the controller there — told its reader to double-click
// a "Start controller.cmd" that was never written into it. A guide that names a missing file
// is worse than one that says nothing: it reads as a broken export. `localController` is what
// the CALLER actually bundled (export/localControl.ts addLocalControlBundle), never a wish.

export interface OnAirGuideOptions {
  /** True only when addLocalControlBundle wrote the relay + launchers into THIS package. */
  localController?: boolean;
  /**
   * The operator page THIS package actually contains, written the way its reader would type the
   * path from where the guide sits: `controlpanel.html` beside a single graphic,
   * `<graphic>/controlpanel.html` one folder down in a show, `show_controlpanel.html` at a show
   * root. Omitted when the package has none - the OGraf, LiveOS and H2R flavours bundle no
   * panel, and naming one there is the same broken-export defect as naming a missing launcher.
   */
  controlPanel?: string;
  /**
   * Markdown the SPX production package adds under the SPX section: what the production uses that
   * SPX cannot carry, and the Update-after-Continue rule (export/spxLeftBehind.ts). Empty or absent
   * adds nothing, so a package without either reads exactly as before.
   */
  spxNotes?: string;
}

export function onAirGuideMd(opts?: OnAirGuideOptions): string {
  const localController = opts?.localController ?? false;
  const panel = opts?.controlPanel ?? '';
  const spxNotes = opts?.spxNotes ? `\n${opts.spxNotes.trimEnd()}\n` : '';
  return `# Getting this package on air

Generated by NoaCG Studio. Everything in this folder is self-contained — relative paths,
bundled fonts and GSAP, no internet needed to render.

## The three rules every browser playout shares

- **Transparency is built in.** Do not add a chroma key. A black/white box behind the graphic
  means the host is forcing an opaque background — clear its custom CSS/background setting.
- **Match the resolution exactly** (the README states this package's canvas). Set the browser
  source to the same numbers; resize the source, never the resulting layer.
- **Match the channel's frame rate** on the browser source.

## SPX Graphics

1. Extract this folder into SPX's \`ASSETS/templates/\` directory.
2. Add the template to a rundown — the operator fields come from the template's own definition.
3. **Play** airs it, **Continue** walks its steps, **Stop** plays it out.
${spxNotes}
## CasparCG

Use the HTML producer. For a folder package, point at the template's own .html file; a
single-file CasparCG export drops straight into the server's template folder:

    CG 1-20 ADD 1 "<template-name>" 1 "<templateData>...</templateData>"
    CG 1-20 PLAY

On CasparCG **2.3.x** the bundled browser is old (Chromium 6x): if you hand-edit template code,
avoid modern syntax like \`?.\` — a too-modern page dies silently with a SyntaxError only in the
server log. Generated code already respects that bar.

## OBS Studio / vMix

Add a **Browser** source (OBS) or **Web Browser** input (vMix), point it at the graphic's .html
file, set width/height to the graphic's resolution, leave the background alone.

## What the fields are called (FIELDS.md)

Every value this package can be given is listed in **FIELDS.md**, with the **ID** a playout
client sends it under — \`f0\`, \`f1\`, … That is the file to keep open beside a CasparCG client:
the client shows you ids, and FIELDS.md is what says which id is the title and which is the name.

${
  localController
    ? `## Local control — the launcher

This package bundles a tiny **local relay**: double-click **"Start controller.cmd"** (Windows)
or **"start-controller.command"** (macOS; Linux: \`./start-controller.sh\`). It serves this folder
at \`http://localhost:<port>/\`, opens the operator page, and relays every command through an
ordered log, so that page reaches a graphic loaded by OBS or vMix, which run their own browser
engine.

1. Start the launcher and keep its window open.
2. Point the OBS/vMix browser source at the graphic ON THAT ADDRESS
   (\`http://localhost:<port>/<graphic>.html\`), not at the file on disk.
3. Operate from the page the launcher opened. Fully offline; no accounts, no internet.

**Operating from inside OBS:** add the same page as a dock. In OBS choose **Docks → Custom
Browser Docks**, give the dock a name, paste the address of the page the launcher opened
(\`http://localhost:<port>/...\`) and click **Apply**. The dock drives the graphic like the
browser tab does, as long as the launcher is running.

**The entrance in OBS.** OBS loads a browser source when the scene collection opens, not when
you cut to it. So in OBS a graphic loaded at its plain address plays its entrance when its source
goes on program, and resets when the source leaves, so the next cut to it plays the entrance
again. Anywhere else it plays when the page loads. Once you play or stop it from the panel, you
are in charge: cuts no longer move it.

macOS note: the .command file may need one-time permission (System Settings → Privacy &
Security), and python3 comes with the OS developer tools.

${panel ? `## The bundled control panel without the launcher

\`${panel}\` can also drive a graphic over a **same-origin browser channel**:

- **Works:** both pages opened from the same web address (http:// or https://, same host and
  port) in the same browser — the launcher above, SPX's own template server, or any web server.
- **Works in OBS too:** an OBS Custom Browser Dock and a browser source on the same http address
  share one browser, so a dock showing \`${panel}\` from the address the source uses pairs with
  the graphic and drives it. A source with **Local file** ticked has no such address; serve the
  folder over http and use that address for both.
- **Does not work:** opening the files straight from disk (\`file://\`) — the browser gives every
  local file its own private origin, so the pages cannot see each other. The panel will tell you
  when nothing is answering.` : ''}`
    : `## Steering these graphics

**The playout host is the controller for this package** — that is why there is no launcher and
no relay in this folder, and why nothing here fights the host for the graphic.

- **SPX:** the rundown. Fill the fields in SPX, then Play / Continue / Stop.
- **CasparCG:** your CasparCG client (the official CasparCG Client, CasparCG Media Scanner
  clients, Sofie, OpenPlayout…). It sends the field ids from **FIELDS.md**; \`CG ADD\` loads the
  template, \`CG PLAY\` airs it, \`CG NEXT\` steps it and \`CG STOP\` plays it out.
- **A double-click local operator page instead?** Export the same graphic (or the same
  production) as the **HTML overlay (OBS / vMix)** target. That package bundles a localhost
  relay and double-click launchers, and is the flavour meant for hosts that have no controller
  of their own. (The launcher filenames are named only in the packages that carry them, so a
  guide never sends you looking for a file that is not there.)

${panel ? `## The fallback: ${panel}

**\`${panel}\` is for the day the playout host is not there** — the machine did not come, the
network died, the rundown is gone. It has every field and every button the graphic declares, and
it needs nothing but a browser.

It pairs only over a **same-origin browser channel**: both pages opened from ONE http(s) address
in ONE browser. So serve this folder over any local web server, open the graphic's own \`.html\`
in one tab and \`${panel}\` in another, and drive it from there.

- Opening the files straight from disk (\`file://\`) never pairs — the browser gives every local
  file its own private origin. The panel says so rather than pretending.
- It cannot reach a graphic loaded by vMix or CasparCG itself: those run their own browser
  engine. Under those hosts, use the host's controls above.
- OBS is the exception: an OBS Custom Browser Dock and a browser source on the same http address
  share one browser. Add a dock (**Docks → Custom Browser Docks**) showing \`${panel}\` from the
  address the browser source uses, and it pairs with the graphic and drives it.` : ''}`
}

## When it does not work

| Symptom | Usually means | Fix |
|---|---|---|
| Layer on air, nothing renders, no error | CasparCG 2.3.x rejected edited JS | Check server log for SyntaxError; remove \`?.\`/\`??\` |
| Black/white box behind the graphic | Host forcing opaque background | Clear custom CSS/background; no chroma key |
| Soft or wrong-sized graphic | Source dimensions do not match the design | Set the source to the graphic's own resolution |
| Control panel buttons do nothing | Pages not same-origin (file://, or different hosts) | Serve both over one http address, or use the host's own controls |
`;
}
