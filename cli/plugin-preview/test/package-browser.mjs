import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import test from 'node:test';
import { execFileSync } from 'node:child_process';
import { cp, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer } from '../server.mjs';
import { readSource } from '../source.mjs';
import { launchBrowser, closeBrowser, newBenchContext } from '../dist/browser.mjs';
import { writePackage } from './package-fixture.mjs';
import { mountHost } from './host-stub.mjs';

const evidence = process.env.NOACG_PREVIEW_EVIDENCE ?? fileURLToPath(new URL('../dist/phase2/', import.meta.url));
const messageContext = (message) => JSON.parse(message.content[0].text.slice(message.content[0].text.indexOf('{')));

test('real square package: font/assets, generated fields/actions, rehearsal PNG and responsive selection stay isolated', { timeout: 60000 }, async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'preview-real-package-'));
  await writePackage(root);
  const original = await readSource(root, 'square.html');
  const server = await createServer({ packageRoot: root, entry: 'square.html' });
  const client = new Client({ name: 'phase2 host stub', version: '1' });
  const [a, b] = InMemoryTransport.createLinkedPair();
  const bench = await newBenchContext(await launchBrowser(), 'https://preview.invalid');
  try {
    await mkdir(evidence, { recursive: true });
    await cp(root, path.join(evidence, 'source-package'), { recursive: true });
    const hashes = Object.fromEntries(await Promise.all(original.sourceFiles.map(async (name) => [name, createHash('sha256').update(await readFile(path.join(root, name))).digest('hex')])));
    await writeFile(path.join(evidence, 'source-hashes.json'), JSON.stringify(hashes, null, 2));
    await server.connect(a);
    await client.connect(b);
    const initial = await client.callTool({ name: 'noacg_preview', arguments: {} });
    assert.ok(!initial.isError, JSON.stringify(initial.content));
    const refused = await client.callTool({ name: 'noacg_preview_rehearse', arguments: { revision: initial.structuredContent.revision, viewId: initial.structuredContent.viewId, cmd: 'update', values: { undeclared: 'never' } } });
    assert.equal(refused.isError, true);
    assert.deepEqual(initial.structuredContent.size, { width: 1080, height: 1080 });
    assert.equal(initial._meta.preview.fields.length, 7);
    assert.deepEqual(initial._meta.preview.fields.map((f) => f.kind), ['text', 'image', 'number', 'select', 'toggle', 'color', 'lines']);
    assert.equal(initial._meta.preview.fields.find((field) => field.key === 'badge').defaultValue, 'images/badge.svg');
    assert.equal(initial._meta.preview.targets.find((target) => target.id === 'headline').bounds.width, 540);
    assert.equal(initial._meta.preview.actions[0].label, 'Goal +1');
    assert.equal(initial._meta.preview.actions[0].disabled, false);
    assert.equal(initial._meta.preview.actions.find((action) => action.event === 'switchLogo').set.badge, 'images/alternate.svg');
    const png = Buffer.from(initial.content[1].data, 'base64');
    assert.equal(png.readUInt32BE(16), 1080);
    assert.equal(png.readUInt32BE(20), 1080);
    await writeFile(path.join(evidence, 'square-initial.png'), png);
    const { page, ui, graphic, errors, calls, consoleMessages, failedRequests } = await mountHost(client, bench, initial);
    await graphic.locator('#panel').waitFor();
    await graphic.locator('#panel').evaluate(() => document.fonts.ready);
    assert.deepEqual(await graphic.locator('body').evaluate(() => ({ faces: [...document.fonts].map((font) => font.status), imageLoaded: document.getElementById('badge').naturalWidth > 0, imageWidth: document.getElementById('badge').getBoundingClientRect().width, family: getComputedStyle(document.getElementById('headline')).fontFamily })), { faces: ['loaded'], imageLoaded: true, imageWidth: 68, family: 'Trial, sans-serif' });
    assert.equal(await ui.getByLabel('Logo', { exact: true }).inputValue(), 'images/badge.svg');
    assert.ok(await graphic.locator('#badge').evaluate((node) => node.src.length > 4000 && node.naturalWidth > 0), 'complete image data survives metadata and Update');
    const stage = await ui.locator('#stage').boundingBox();
    assert.ok(Math.abs(stage.width - stage.height) < 1);
    await ui.getByLabel('Headline', { exact: true }).fill('Evening report from the studio');
    await ui.getByLabel('Score', { exact: true }).fill('7');
    await ui.getByLabel('Edition', { exact: true }).selectOption('REPLAY');
    await ui.getByLabel('Notes', { exact: true }).fill('A longer first line\nA second line');
    await ui.getByRole('button', { name: 'Update preview', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    await graphic.locator('#headline').filter({ hasText: 'Evening report from the studio' }).waitFor();
    assert.equal(await graphic.locator('#headline').textContent(), 'Evening report from the studio');
    assert.equal(await graphic.locator('#score').textContent(), '7');
    assert.equal(await graphic.locator('#edition').textContent(), 'REPLAY');
    assert.ok(await graphic.locator('#badge').evaluate((node) => node.src.length > 4000 && node.naturalWidth > 0));
    await ui.getByRole('button', { name: 'Alternate logo', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    assert.equal(await ui.getByLabel('Logo', { exact: true }).inputValue(), 'images/alternate.svg');
    assert.ok(await graphic.locator('#badge').evaluate((node) => node.naturalWidth > 0 && atob(node.src.split(',')[1]).includes('#48a5ff')));
    await ui.getByRole('button', { name: 'Update preview', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    assert.equal(await ui.getByLabel('Logo', { exact: true }).inputValue(), 'images/alternate.svg');
    assert.ok(await graphic.locator('#badge').evaluate((node) => node.naturalWidth > 0 && atob(node.src.split(',')[1]).includes('#48a5ff')), 'Update preserves the image selected by an authored operator action');
    await ui.getByRole('button', { name: 'Goal +1', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    await graphic.locator('#score').filter({ hasText: /^8$/ }).waitFor();
    assert.equal(await graphic.locator('#score').textContent(), '8');
    assert.equal(await ui.getByLabel('Score', { exact: true }).inputValue(), '8');
    // Known fields without data-preview-target are named and measured after layout changes.
    const select = ui.getByRole('button', { name: 'Select Headline', exact: true });
    await select.click();
    await ui.locator('#request').fill('Give this headline more emphasis');
    await ui.getByRole('button', { name: 'Send change to this task' }).click();
    await ui.getByRole('status').filter({ hasText: 'Change and image sent' }).waitFor();
    const request = (await page.evaluate(() => window.received))[0];
    const context = messageContext(request);
    assert.equal(context.sampleValues.score, '8');
    assert.equal(context.sampleValues.badge, 'images/alternate.svg');
    assert.ok(context.rehearsal.operations.some((operation) => operation.event === 'switchLogo'));
    assert.equal(context.rehearsal.last, 'event');
    assert.equal(context.selection.id, 'headline');
    assert.equal(context.revision, original.revision);
    assert.notEqual(request.content[1].data, initial.content[1].data);
    await writeFile(path.join(evidence, 'square-rehearsed.png'), Buffer.from(request.content[1].data, 'base64'));
    const within = (actual, expected, tolerance = 2) => assert.ok(Math.abs(actual - expected) <= tolerance, `${actual} != ${expected}`);
    async function checkHighlight() {
      const bounds = context.selection.bounds;
      const layer = await ui.locator('#selection-layer').boundingBox();
      const selected = await ui.locator('#highlight').boundingBox();
      within(selected.x, layer.x + bounds.x / 1080 * layer.width);
      within(selected.y, layer.y + bounds.y / 1080 * layer.height);
      within(selected.width, bounds.width / 1080 * layer.width);
      within(selected.height, bounds.height / 1080 * layer.height);
    }
    await checkHighlight();
    await page.screenshot({ path: path.join(evidence, 'panel-wide.png') });
    await page.evaluate(() => { document.getElementById('app').style.width = '460px'; });
    await ui.locator('#stage').evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    await checkHighlight();
    // Chromium/Playwright reports nested-frame boundingBox in unscaled frame pixels.
    // Read the actual DOM rect and map through the iframe's rendered scale instead.
    const local = await graphic.locator('#headline').evaluate((node) => { const b = node.getBoundingClientRect(); return { x: b.x, y: b.y, width: b.width, height: b.height }; });
    const frame = await ui.locator('#graphic').boundingBox();
    const scale = frame.width / 1080;
    const actual = { x: frame.x + local.x * scale, y: frame.y + local.y * scale, width: local.width * scale, height: local.height * scale };
    const selected = await ui.locator('#highlight').boundingBox();
    within(actual.x, selected.x); within(actual.y, selected.y); within(actual.width, selected.width); within(actual.height, selected.height);
    await ui.locator('#mode').selectOption('region');
    assert.equal(await select.isVisible(), false);
    const area = await ui.locator('#selection-layer').boundingBox();
    await page.mouse.move(area.x + area.width * .15, area.y + area.height * .2);
    await page.mouse.down();
    await page.mouse.move(area.x + area.width * .75, area.y + area.height * .65);
    await page.mouse.up();
    await ui.getByRole('button', { name: 'Send change to this task' }).click();
    await ui.getByRole('status').filter({ hasText: 'Change and image sent' }).waitFor();
    const region = messageContext((await page.evaluate(() => window.received))[1]);
    assert.equal(region.selection.kind, 'region');
    within(region.selection.bounds.x, 162, 4); within(region.selection.bounds.width, 648, 4);
    await page.screenshot({ path: path.join(evidence, 'panel-narrow-region.png') });
    const count = calls.length;
    const isolation = await graphic.locator('body').evaluate(async () => {
      const readable = (read) => { try { read(); return true; } catch { return false; } };
      parent.postMessage({ jsonrpc: '2.0', id: 'forged', method: 'tools/call', params: { name: 'noacg_preview', arguments: {} } }, '*');
      parent.parent.postMessage({ jsonrpc: '2.0', id: 'forged-host', method: 'tools/call', params: { name: 'noacg_preview', arguments: {} } }, '*');
      const network = await fetch('https://example.invalid/credential-probe').then(() => true, () => false);
      const file = await fetch('file:///etc/passwd').then(() => true, () => false);
      return { network, file, parent: readable(() => parent.document.body), cookies: readable(() => document.cookie), storage: readable(() => localStorage.getItem('token')), openai: typeof window.openai, bridge: typeof window.noacgBridge };
    });
    assert.deepEqual(isolation, { network: false, file: false, parent: false, cookies: false, storage: false, openai: 'undefined', bridge: 'undefined' });
    await page.evaluate(() => new Promise((resolve) => setTimeout(resolve, 80)));
    assert.equal(calls.length, count, 'graphic messages cannot invoke trusted tools');
    await ui.getByRole('button', { name: 'Out', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    assert.equal(await graphic.locator('#panel').evaluate((node) => getComputedStyle(node).opacity), '0');
    assert.equal(await ui.getByRole('button', { name: 'Goal +1', exact: true }).isDisabled(), true);
    await ui.getByRole('button', { name: 'Take', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    assert.equal(await graphic.locator('#panel').evaluate((node) => getComputedStyle(node).opacity), '1');
    await ui.getByRole('button', { name: 'Reset rehearsal', exact: true }).click();
    await ui.getByRole('status').filter({ hasText: 'Ready' }).waitFor();
    await graphic.locator('#score').filter({ hasText: /^2$/ }).waitFor();
    assert.equal(await graphic.locator('#score').textContent(), '2');
    assert.equal(await ui.getByRole('button', { name: 'Send change to this task' }).isDisabled(), true);
    assert.equal((await readSource(root, 'square.html')).revision, original.revision, 'rehearsal never writes source');
    await writeFile(path.join(evidence, 'receipt.json'), JSON.stringify({ implementation: { sha: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), dirtyPaths: execFileSync('git', ['status', '--short'], { encoding: 'utf8' }).trim(), candidatePackageVersion: JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')).version, mcpSdkDependencyVersion: JSON.parse(await readFile(new URL('../node_modules/@modelcontextprotocol/sdk/package.json', import.meta.url), 'utf8')).version, nativeCodexInstallationObserved: false }, revision: original.revision, sourceFiles: original.sourceFiles, size: initial.structuredContent.size, context, region, isolation, errors, consoleMessages, failedRequests }, null, 2));
    assert.deepEqual(errors, []);
    process.stdout.write('Phase-2 package/browser checks passed; Windows rendered desktop inspection remains unverified.\n');
  } finally {
    await bench.close(); await client.close(); await server.close(); await closeBrowser();
    await rm(root, { recursive: true, force: true });
  }
});
