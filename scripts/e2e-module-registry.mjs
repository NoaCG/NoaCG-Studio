#!/usr/bin/env node
// gate: build
// guards: e2e/**, src/e2eRegistry.ts
//
// THE E2E BUILD'S MODULE REGISTRY LISTS EVERY SOURCE MODULE A BROWSER SPEC IMPORTS BY A LITERAL PATH.
//
//   npm run check:e2e-registry                     # check: fails when the file is stale
//   node scripts/e2e-module-registry.mjs --write   # regenerate src/e2eRegistry.ts
//
// Specs reach the app's modules from inside the page with `__noacgImport('/src/x.ts')`. The e2e
// build (src/app/e2eModules.ts) answers those from src/e2eRegistry.ts, its own entry at a fixed
// URL, loaded on the first call, that imports each listed module statically, so the registry hands
// back the page's own instance.
// A spec that imports a module the registry does not list fails on the e2e build only, so the
// list is generated from the specs and this check keeps it current. It also refuses a literal
// in-page `import('/src/…')` left in a spec, in any form: the built app serves no /src URL, so
// only the door works there. A deliberate fresh copy (`?t=`, `'/src/x.ts' + bust`) is let through:
// only the dev server can serve one, so its spec runs on the dev server.
//
// ONE CHUNK, NOT ONE CHUNK PER MODULE. Measured on run #1967's probe: a lazy `import.meta.glob`
// over the same paths split the app into 491 files and doubled the boot (926 ms against 488).
// A static registry leaves the app's own chunks alone and costs one load, about 0.4 s, the first
// time a test asks.
//
// LAZY lists the modules whose top level does something to the page (configures Monaco's workers,
// binds the working document). The static chunk would run them at a spec's first import of
// anything; lazily they run only when asked for, as on the dev server.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { measured } from './measured.mjs';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = join(ROOT, 'src/e2eRegistry.ts');
export const LAZY = new Set(['/src/monacoSetup.ts', '/src/store/authoringProjects.ts']);
/** Modules outside src/ a page reads through the door: the offline guard's env probe, which tells
 *  what the page was built against (e2e/_offline-guard.ts). */
export const EXTRA = ['/e2e/_env-probe.ts'];

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : /\.(ts|tsx|mjs|js)$/.test(name) ? [path] : [];
  });
}

/** Every literal `import('/src/….ts')` or `__noacgImport('/src/….ts')` in the specs, without a query string (a `?t=` import asks
 *  for a deliberate second copy, which only the dev server can serve). */
export function specImports(texts) {
  const found = new Set();
  for (const text of texts) {
    for (const m of text.matchAll(/(?:\bimport|__noacgImport)\(\s*['"`](\/src\/[\w./-]+\.tsx?)['"`]\s*\)/g)) found.add(m[1]);
  }
  return [...found].sort();
}

/** In-page `import('/src/…')` calls left in the specs, in any form (`as string`, a variable
 *  suffix), as `file:line`. The built app serves no /src URLs, so a spec reaches a module through
 *  `__noacgImport` instead. Allowed: a type position (`typeof import(...)`), and a deliberate fresh
 *  copy (`?t=` in the literal, or a suffix appended with `+`), which only the dev server can serve
 *  and which the spec therefore runs there, and a mention in a comment. */
export function plainImports(entries) {
  const found = [];
  for (const [file, text] of entries) {
    for (const m of text.matchAll(/(?<!typeof\s+)\bimport\(\s*(['"`])(\/src\/[^'"`]*)\1(\s*\+)?/g)) {
      if (m[2].includes('?t=') || m[3]) continue;
      const lineStart = text.lastIndexOf('\n', m.index) + 1;
      if (/^\s*(\/\/|\*)/.test(text.slice(lineStart, m.index))) continue; // a comment line
      found.push(`${file}:${text.slice(0, m.index).split('\n').length}`);
    }
  }
  return found;
}

/** The import path of `/src/x.ts` or `/e2e/x.ts` from src/e2eRegistry.ts. */
const rel = (p) => (p.startsWith('/src/') ? '.' + p.slice('/src'.length) : '..' + p);

export function registrySource(paths) {
  const eager = paths.filter((p) => !LAZY.has(p));
  const lazy = paths.filter((p) => LAZY.has(p));
  return [
    '// GENERATED by scripts/e2e-module-registry.mjs --write from the specs\' `import(\'/src/…\')` calls.',
    '// Do not edit. Only the e2e build loads it (src/app/e2eModules.ts).',
    ...eager.map((p, i) => `import * as m${i} from '${rel(p)}';`),
    '',
    'export const MODULES: Record<string, unknown> = {',
    ...eager.map((p, i) => `  '${p}': m${i},`),
    '};',
    '',
    'export const LAZY: Record<string, () => Promise<unknown>> = {',
    ...lazy.map((p) => `  '${p}': () => import('${rel(p)}'),`),
    '};',
    '',
  ].join('\n');
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const entries = files(join(ROOT, 'e2e')).map((f) => [relative(ROOT, f), readFileSync(f, 'utf8')]);
  const texts = entries.map(([, text]) => text);
  const plain = plainImports(entries);
  if (plain.length) {
    console.error(`e2e-module-registry: a spec imports a source module directly; use __noacgImport('/src/…') so it also runs on the e2e build:\n  ${plain.join('\n  ')}`);
    process.exit(1);
  }
  const paths = [...specImports(texts), ...EXTRA].sort();
  measured(paths.length, 'source modules the specs import');
  const missing = paths.filter((p) => !existsSync(join(ROOT, p)));
  if (missing.length) {
    console.error(`e2e-module-registry: specs import modules that do not exist:\n  ${missing.join('\n  ')}`);
    process.exit(1);
  }
  const want = registrySource(paths);
  if (process.argv.includes('--write')) {
    writeFileSync(OUT, want);
    console.log(`e2e-module-registry: wrote ${relative(ROOT, OUT)} (${paths.length} modules)`);
  } else if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== want) {
    console.error('e2e-module-registry: src/e2eRegistry.ts is stale; run node scripts/e2e-module-registry.mjs --write');
    process.exit(1);
  } else {
    console.log(`e2e-module-registry: ok (${paths.length} modules)`);
  }
}
