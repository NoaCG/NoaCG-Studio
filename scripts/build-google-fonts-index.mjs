// Regenerate src/model/googleFontsIndex.ts - the searchable catalogue of the Google Fonts
// library (names and weights only; no font bytes are downloaded or checked in).
//
// Why a checked-in index rather than a live query: the picker has to answer a keystroke, and
// an offline build has to keep working. The index is names, so it is small; the FILE for the
// one family a user picks is fetched at design time and embedded in the template, which is
// what keeps playout free of any network dependency
// (`root/keep-generated-template-self-contained-runtime`).
//
// Time-driven, never commit-driven (docs/STACK_FRESHNESS.md): re-run it when the library has
// visibly moved on. A family that appears after the last run is still reachable - the picker
// takes a typed name it does not know and asks Google for it directly.
//
//   node scripts/build-google-fonts-index.mjs
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://fonts.google.com/metadata/fonts';
const OUT = new URL('../src/model/googleFontsIndex.ts', import.meta.url);

const text = await fetch(SOURCE).then((r) => {
  if (!r.ok) throw new Error(`${SOURCE} answered ${r.status}`);
  return r.text();
});
// The endpoint prefixes its JSON with an anti-JSON-hijacking guard.
const meta = JSON.parse(text.replace(/^\)\]\}'\s*/, ''));
const families = meta.familyMetadataList;
if (!Array.isArray(families) || families.length < 500) {
  throw new Error(`Unexpected metadata shape (${families?.length} families)`);
}

// Popularity order, so the picker's first answers are the faces people actually use.
families.sort((a, b) => (a.popularity ?? 1e9) - (b.popularity ?? 1e9));

const CATEGORY = { 'Sans Serif': 's', Serif: 'f', Display: 'd', Handwriting: 'h', Monospace: 'm' };

const rows = families.map((f) => {
  // Upright weights only: the index drives a weight picker, and an italic file is a separate
  // face the single-file embed has no way to select between.
  const weights = Object.keys(f.fonts ?? {})
    .filter((w) => /^\d+$/.test(w))
    .map(Number)
    .sort((a, b) => a - b);
  return `${f.family}|${CATEGORY[f.category] ?? 's'}|${weights.join(' ')}`;
});

const file = `// GENERATED by scripts/build-google-fonts-index.mjs - do not edit by hand.
// ${families.length} families from ${SOURCE}, in popularity order.
//
// One line per family: name | category (s/f/d/h/m) | the upright weights it publishes.
// Names only - no font bytes. src/model/googleFonts.ts parses it lazily.

export const GOOGLE_FONTS_GENERATED = '${new Date().toISOString().slice(0, 10)}';

export const GOOGLE_FONTS_RAW = \`${rows.join('\n')}\`;
`;

writeFileSync(OUT, file, 'utf8');
console.log(`Wrote ${families.length} families to src/model/googleFontsIndex.ts`);
