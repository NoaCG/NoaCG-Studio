// The title and description of a landing pull request, written for a person.
//
// A pull request is the only part of a landing that a human ever reads. Until now it carried one
// machine line - "Landed by the queue (`npm run queue:merge`). reviewed by /check at abc12345
// (pass)." - which says who queued it and nothing about what it does. The owner asked for the
// opposite: what changed, optionally why, and how it was tested, in words a non-technical reader
// follows (2026-09-07).
//
// The source is the branch's own commits. Commit messages here are already required to explain
// the actual change and to read as if a person wrote them (root `AGENTS.md`, "Git"), so the
// description is built from them rather than from a summary somebody has to remember to type.
// The one thing commits cannot supply is the why, so `--why` carries a sentence when there is one.
//
// Since 2026-10-08 the shape is smaller still: two sentences, a Risk line, details closed. The
// Risk line is the queuing session's own sentence (`--risk`); without one it is derived only when
// the changed paths make it certain, and otherwise left out, because "not assessed" on every pull
// request was noise.
//
// Pure string work, kept out of scripts/jobs.mjs so it can be tested without a repository.

/** How many commit lines a description lists before it starts counting the rest. */
const MAX_LINES = 12;

/**
 * The marker that says this description was generated.
 *
 * Queueing a branch twice must refresh a description it wrote - the commit list has moved, and a
 * stale list is worse than none. It must NOT overwrite one a person typed. The marker is how the
 * two are told apart: rewrite a body carrying it, leave every other body alone.
 */
export const GENERATED_MARKER = '<!-- noacg:queue-merge -->';

/** The old one-line body, which predates the marker and is safe to replace. */
const LEGACY_BODY = /^Landed by the queue \(`npm run queue:merge`\)\./;

/** True when `body` is ours to rewrite: absent, generated by us, or the pre-marker one-liner. */
export function isGeneratedBody(body) {
  const text = (body ?? '').trim();
  if (text === '') return true;
  return text.includes(GENERATED_MARKER) || LEGACY_BODY.test(text);
}

/**
 * The pull request title: the FIRST commit on the branch, not the last.
 *
 * The first commit is the one that named the work. The last is routinely a tail - "Fix the review
 * findings", "Keep the lint clean" - which is a poor name for the whole change.
 */
export function pullRequestTitle(subjects, branch) {
  const first = subjects.find((s) => s.trim() !== '');
  return (first ?? branch).slice(0, 120);
}

/** Cut `text` to its first `count` sentences, whitespace collapsed. */
export function firstSentences(text, count = 2) {
  const flat = (text ?? '').replace(/\s+/g, ' ').trim();
  if (flat === '') return '';
  const sentences = flat.match(/(?:[^.!?]|[.!?]+(?!\s|$))+(?:[.!?]+(?=\s|$)|$)/g) ?? [flat];
  return sentences.slice(0, count).map((s) => s.trim()).join(' ');
}

/** The one risk the changed paths derive. */
const DOCS_ONLY = 'low, docs only.';

/**
 * The Risk line's text: the queuing session's sentence, else one the changed paths make certain,
 * else '' (no line). A branch that changes only Markdown under docs/ cannot break the product, and
 * CI still builds it before it lands. Anything else needs a person's judgement.
 */
export function riskText(risk = '', paths = []) {
  const given = risk.replace(/\s+/g, ' ').trim().replace(/^risk:\s*/i, '');
  if (given !== '') return given;
  const changed = paths.map((p) => p.trim()).filter(Boolean);
  if (changed.length > 0 && changed.every((p) => /^docs\/.+\.md$/i.test(p))) return DOCS_ONLY;
  return '';
}

/**
 * The Risk sentence a session gave on an earlier queueing, so queueing again does not drop it. A
 * derived one is not carried over: the branch may have grown past docs since, so it is derived anew.
 */
export function riskFromBody(body = '') {
  if (!isGeneratedBody(body)) return '';
  const earlier = /^Risk: (.+)$/m.exec(body ?? '')?.[1].trim() ?? '';
  return earlier === DOCS_ONLY ? '' : earlier;
}

/**
 * The issues the branch's commit messages close, by GitHub's own keywords (`Closes #12`,
 * `Fixes #3`, `Resolves #7`), each once and in order. The backlog is GitHub Issues, and a branch
 * that finishes one says so in a commit; the pull request repeats it so GitHub links the two and
 * closes the issue when the queue merges it.
 */
export function closedIssues(messages = '') {
  const found = new Set();
  for (const match of String(messages).matchAll(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)\b/gi)) {
    found.add(Number(match[1]));
  }
  return [...found].sort((a, b) => a - b);
}

/**
 * The description (owner, 2026-10-08: simple and clean): two plain sentences from the main
 * commit's body, one "Risk:" line (`riskText`), a `Closes #n` line per issue the commits close,
 * and the run details in a closed block. No template sections, and no image unless `image` (a
 * URL) is given, which is for a visual change.
 *
 * `subjects` are the branch's non-merge commit subjects, oldest first; the first is the main
 * commit. `message` is that commit's body; with none, its subject stands in. `tested` is the
 * review verdict as the queue records it. `why`, when given, goes in the details. `paths` are the
 * files the branch changes, used only to derive a risk nobody gave. `closes` are issue numbers
 * (`closedIssues`).
 */
export function pullRequestBody({ subjects = [], message = '', tested = '', why = '', risk = '', paths = [], image = '', closes = [] } = {}) {
  const changes = subjects.filter((s) => s.trim() !== '');
  let summary = firstSentences(message);
  if (summary === '') {
    summary = changes.length > 0 ? changes[0].trim().replace(/[.!?]*$/, '.') : 'This branch has no commits of its own.';
  }

  const lines = [summary];
  const risky = riskText(risk, paths);
  if (risky !== '') lines.push('', `Risk: ${risky}`);
  if (closes.length > 0) lines.push('', ...closes.map((number) => `Closes #${number}`));
  if (image.trim() !== '') lines.push('', `![Screenshot](${image.trim()})`);

  const details = [];
  if (why.trim() !== '') details.push(`Why: ${why.trim()}`);
  if (tested.trim() !== '') details.push(`Tested: ${tested.trim()}`);
  details.push('GitHub runs the build and every test this change can affect before the queue merges it.', '');
  const shown = changes.slice(0, MAX_LINES);
  details.push(...shown.map((subject) => `- ${subject}`));
  if (changes.length > shown.length) details.push(`- and ${changes.length - shown.length} more`);

  lines.push('', '<details>', '<summary>Details</summary>', '', ...details, '', '</details>', '', GENERATED_MARKER);
  return lines.join('\n');
}
