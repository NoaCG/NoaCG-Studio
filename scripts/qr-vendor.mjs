// Writes src/templates/shared/qrEncoder.min.js: the QR encoder a Join card carries inside its own
// script, so an exported graphic draws its QR with no network (interaction spec, Graphics).
// It is qrcode-generator (MIT, Kazuhiko Arase), minified from the installed package.
// scripts/qr-vendor.test.mjs fails when the file and the package disagree; run this to refresh it:
//   node scripts/qr-vendor.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { minifySync } from 'rolldown/experimental';

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));

export const VENDORED = root('src/templates/shared/qrEncoder.min.js');

export function vendoredText() {
  const pkg = JSON.parse(readFileSync(root('node_modules/qrcode-generator/package.json'), 'utf8'));
  const source = readFileSync(root('node_modules/qrcode-generator/dist/qrcode.js'), 'utf8');
  const { code: minified } = minifySync('qrcode.js', source, { compress: true, mangle: true });
  // The minifier writes the string '$' as a template literal. Inside a graphic's script that
  // reads as the replace pattern $` wherever the script is spliced into a page with
  // String.replace (the studio's preview does), which cuts the script short. A plain string is
  // the same value and no pattern.
  const code = minified.replace(/`\$`/g, '"$"');
  return (
    `/* qrcode-generator ${pkg.version} (c) 2009 Kazuhiko Arase, MIT license, https://github.com/kazuhikoarase/qrcode-generator. ` +
    `"QR Code" is a registered trademark of DENSO WAVE INCORPORATED. Generated by scripts/qr-vendor.mjs. */\n${code}`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(VENDORED, vendoredText());
  console.log(`wrote ${VENDORED}`);
}
